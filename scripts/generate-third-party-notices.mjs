import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lockPath = path.join(repositoryRoot, 'package-lock.json');
const outputPath = path.join(repositoryRoot, 'THIRD_PARTY_LICENSES.md');
const checkOnly = process.argv.includes('--check');

const lock = JSON.parse(await readFile(lockPath, 'utf8'));
if (lock.lockfileVersion !== 3 || !lock.packages?.['']) {
    throw new Error('Expected an npm lockfileVersion 3 package lock with a root package entry.');
}

const rootPackage = lock.packages[''];
const directRuntime = new Set(Object.keys(rootPackage.dependencies ?? {}));
const directDevelopment = new Set(Object.keys(rootPackage.devDependencies ?? {}));
const entries = [];

for (const [packagePath, locked] of Object.entries(lock.packages)) {
    if (!packagePath || !locked?.version || !packagePath.includes('node_modules/')) continue;
    const name = packagePath.slice(packagePath.lastIndexOf('node_modules/') + 'node_modules/'.length);
    const installedManifest = await readInstalledManifest(packagePath);
    const license = normalizeLicense(locked.license ?? installedManifest?.license ?? installedManifest?.licenses);
    if (!license) {
        throw new Error(`No license metadata found for ${name}@${locked.version} (${packagePath}).`);
    }
    entries.push({
        name,
        version: locked.version,
        license,
        use: classifyUse(packagePath, name, locked),
        source: describeSource(locked.resolved),
    });
}

entries.sort((left, right) =>
    left.name.localeCompare(right.name) ||
    left.version.localeCompare(right.version, undefined, { numeric: true }) ||
    left.use.localeCompare(right.use)
);

const runtimeCount = entries.filter((entry) => entry.use.includes('runtime')).length;
const developmentCount = entries.length - runtimeCount;
const lines = [
    '# Third-party dependency license inventory',
    '',
    '<!-- Generated by scripts/generate-third-party-notices.mjs. Do not edit by hand. -->',
    '',
    `This inventory was generated from \`package-lock.json\` (lockfile version ${lock.lockfileVersion}). It contains ${entries.length} resolved package entries: ${runtimeCount} runtime or optional-runtime entries and ${developmentCount} development entries. Multiple versions of one package are listed separately.`,
    '',
    'License identifiers come from the lockfile and installed package manifests. The dependency package itself remains the authoritative source for its complete license and notice text. Review bundled browser assets and corresponding-source obligations separately before each release.',
    '',
    '| Package | Version | License | Use | Source |',
    '|---|---:|---|---|---|',
    ...entries.map(
        (entry) =>
            `| ${escapeCell(entry.name)} | ${escapeCell(entry.version)} | ${escapeCell(entry.license)} | ${escapeCell(entry.use)} | ${escapeCell(entry.source)} |`
    ),
    '',
];
const generated = lines.join('\n');

if (checkOnly) {
    const current = await readFile(outputPath, 'utf8').catch(() => '');
    if (current.replaceAll('\r\n', '\n') !== generated) {
        throw new Error('THIRD_PARTY_LICENSES.md is missing or stale. Run npm run licenses:update.');
    }
    console.log(`Verified ${entries.length} third-party package license entries.`);
} else {
    await writeFile(outputPath, generated, 'utf8');
    console.log(`Wrote ${entries.length} third-party package license entries to THIRD_PARTY_LICENSES.md.`);
}

async function readInstalledManifest(packagePath) {
    const manifestPath = path.join(repositoryRoot, packagePath, 'package.json');
    try {
        return JSON.parse(await readFile(manifestPath, 'utf8'));
    } catch {
        return null;
    }
}

function normalizeLicense(value) {
    if (typeof value === 'string') return value.trim();
    if (Array.isArray(value)) {
        const licenses = value
            .map((entry) => (typeof entry === 'string' ? entry : entry?.type))
            .filter((entry) => typeof entry === 'string' && entry.trim())
            .map((entry) => entry.trim());
        return [...new Set(licenses)].join(' OR ');
    }
    if (value && typeof value.type === 'string') return value.type.trim();
    return '';
}

function classifyUse(packagePath, name, locked) {
    const isTopLevel = packagePath === `node_modules/${name}`;
    if (isTopLevel && directRuntime.has(name)) return 'direct runtime';
    if (isTopLevel && directDevelopment.has(name)) return 'direct development';
    if (locked.dev) return 'development';
    if (locked.optional) return 'optional runtime';
    return 'runtime';
}

function describeSource(resolved) {
    if (!resolved) return 'npm lock metadata';
    if (resolved.startsWith('https://registry.npmjs.org/')) return 'npm registry';
    if (resolved.startsWith('git+')) return resolved.replace(/^git\+ssh:\/\/git@github\.com\//, 'github:');
    return resolved;
}

function escapeCell(value) {
    return String(value).replaceAll('|', '\\|').replaceAll('\r', ' ').replaceAll('\n', ' ');
}
